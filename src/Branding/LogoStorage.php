<?php

declare(strict_types=1);

namespace App\Branding;

use Symfony\Component\DependencyInjection\Attribute\Autowire;

/** Logo files on disk (var/branding by default, which Symfony already expects to be writable). */
final class LogoStorage
{
    public function __construct(
        #[Autowire('%kernel.project_dir%/var/branding')]
        private readonly string $directory,
    ) {
    }

    public function write(string $name, string $bytes): void
    {
        if (!is_dir($this->directory) && !@mkdir($this->directory, 0775, true) && !is_dir($this->directory)) {
            throw new \RuntimeException('Cannot create '.$this->directory);
        }
        if (false === file_put_contents($this->path($name), $bytes)) {
            throw new \RuntimeException('Cannot write '.$this->path($name));
        }
    }

    public function delete(?string $name): void
    {
        if (null !== $name && is_file($this->path($name))) {
            @unlink($this->path($name));
        }
    }

    public function path(string $name): string
    {
        // Names are generated by BrandingService; basename() is a second guard against traversal.
        return $this->directory.'/'.basename($name);
    }
}
